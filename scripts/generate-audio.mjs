// Generates the "listen" clips for the built-in adhkar with OpenAI text-to-speech.
//
//   OPENAI_API_KEY=... node scripts/generate-audio.mjs [--force] [--only id1,id2]
//
// Writes public/audio/<id>.mp3 (one clip per distinct Arabic text; items that share a
// text share a clip) and src/shared/audio.ts, the id -> clip map the island uses.
// Whole surahs are skipped: recitation needs tajwid, which text-to-speech can't do.
// Every clip must be checked by a native Arabic speaker before release.
// The API returns 128 kb/s MP3, far more than speech needs; the shipped clips are
// re-encoded to a third of that size with: ffmpeg -i in.mp3 -ac 1 -ar 24000 -b:a 48k out.mp3

import { existsSync, mkdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { ISTIGHFAR, PACKS } = await import(pathToFileURL(join(root, "src/shared/content.ts")).href);

const MODEL = "gpt-4o-mini-tts-2025-12-15";
const VOICE = "cedar";
const INSTRUCTIONS =
  "Read this Arabic dhikr aloud in clear Classical Arabic (fusha), exactly as written, " +
  "pronouncing every vowel mark (tashkeel), shadda and long vowel precisely. Calm, reverent " +
  "and unhurried, like a teacher reading adhkar slowly for students to repeat after him. " +
  "Do not add, skip or translate any words.\n" +
  "The text is already written for stopping (waqf): a word ending in sukun (ْ) is the last word " +
  "before a pause, so stop on it without any final vowel, exactly as written, and pause briefly at " +
  "every comma. Never add a vowel sound (such as -i, -u or -a) to the end of a word marked with sukun.";
/** Recited Qur'an (whole surahs): left to a human reciter. */
const SKIP = new Set(["ikhlas", "falaq", "nas"]);

const args = process.argv.slice(2);
const force = args.includes("--force");
const only = args.includes("--only") ? new Set(args[args.indexOf("--only") + 1].split(",")) : null;
const key = process.env.OPENAI_API_KEY;
if (!key) throw new Error("Set OPENAI_API_KEY");

const items = [...Object.values(ISTIGHFAR), ...Object.values(PACKS).flatMap((p) => p.items)];
const base = (id) => id.replace(/^[mepf]-/, "");
/** First id seen for each text names its clip. */
const clipFor = new Map();
for (const d of items) if (!SKIP.has(base(d.id)) && !clipFor.has(d.ar)) clipFor.set(d.ar, d.id);

const outDir = join(root, "public/audio");
mkdirSync(outDir, { recursive: true });

/**
 * Arabic stops on a sukun (waqf): the last word before a pause loses its final vowel or
 * tanween. The voice reads the written marks literally, so the text it receives is
 * rewritten the way it should be heard: قَدِيرٌ → قَدِيرْ, سَمِيعًا → سَمِيعَا, رَحْمَةٌ → رَحْمَهْ.
 */
const VOWELS = /[ً-ِْ]+$/; // tanween, short vowels, sukun (not shadda or dagger alif)
function stopOn(word) {
  if (/ًا?$|اً$/.test(word)) return word.replace(/ً/g, "").replace(/[َ]?$/, "") + (word.endsWith("ا") || /اً$/.test(word) ? "" : "ا");
  let w = word.replace(VOWELS, "");
  if (w.endsWith("ة")) return w.slice(0, -1) + "هْ";
  if (/[اىآ]$/.test(w) || w.endsWith("ّ")) return w;
  return w + "ْ";
}
export function forSpeech(text) {
  return text
    .split(/([،,.؛;:!؟?\n]+)/)
    .map((part, i) => {
      if (i % 2 === 1) return part; // the punctuation itself
      const m = part.match(/^(.*?)(\S+)(\s*)$/s);
      return m ? m[1] + stopOn(m[2]) + m[3] : part;
    })
    .join("");
}

async function speak(text, file) {
  text = forSpeech(text);
  for (let attempt = 1; ; attempt++) {
    const res = await fetch("https://api.openai.com/v1/audio/speech", {
      method: "POST",
      headers: { Authorization: `Bearer ${key}`, "Content-Type": "application/json" },
      body: JSON.stringify({ model: MODEL, voice: VOICE, input: text, instructions: INSTRUCTIONS, response_format: "mp3" }),
    });
    if (res.ok) return writeFileSync(file, Buffer.from(await res.arrayBuffer()));
    if (attempt >= 3) throw new Error(`${file}: ${res.status} ${await res.text()}`);
    await new Promise((r) => setTimeout(r, 2000 * attempt));
  }
}

const jobs = [...clipFor.entries()].filter(([, id]) => (!only || only.has(id)) && (force || !existsSync(join(outDir, `${id}.mp3`))));
let next = 0;
await Promise.all(
  Array.from({ length: 5 }, async () => {
    while (next < jobs.length) {
      const [text, id] = jobs[next++];
      await speak(text, join(outDir, `${id}.mp3`));
      console.log("ok", id);
    }
  }),
);

const map = Object.fromEntries(items.filter((d) => clipFor.has(d.ar)).map((d) => [d.id, `/audio/${clipFor.get(d.ar)}.mp3`]));
writeFileSync(
  join(root, "src/shared/audio.ts"),
  `// Generated by scripts/generate-audio.mjs: dhikr id -> "listen" clip.\nexport const AUDIO: Record<string, string> = ${JSON.stringify(map, null, 2)};\n`,
);
console.log(`${jobs.length} generated, ${clipFor.size} clips, ${Object.keys(map).length} adhkar covered`);
